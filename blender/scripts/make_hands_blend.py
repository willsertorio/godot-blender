"""Viewable .blend per gun with both hand styles -> blender/hands_<gun>.blend (for review in Blender).

    blender -b -P blender/scripts/make_hands_blend.py

The game assets are generated by build_hands.py / pose_wrad.py straight to .glb; this script only
assembles them for looking at. Collections (toggle the eye icons):
  Gun          pistol.glb / rifle.glb, base-colour texture hooked up
  HandModel    rigid_<gun>.glb  (your rigid hand, pose_rigid_hand.py; the in-game default). Pose it here,
               save, then: blender -b -P blender/scripts/read_rigid_hand_poses.py (keeps your pose)
  Hands        hands_<gun>.glb  (metaball gloves, hidden by default)
  ArmsFull     arms_<gun>.glb   (WRAD arms, H key in game), placed at -hip like WeaponHolder does
  GameCamera   the viewmodel camera (FOV 54) at the hip pose: Numpad 0 shows what the player sees
Gun frame: origin at the grip, barrel along +Y. Editing here does NOT change the game; tell Claude
what to change (or edit the numbers in build_hands.py) and the glbs get rebuilt.
"""
import math
import os

import bpy
from mathutils import Vector

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MODELS = os.path.join(ROOT, "assets", "models")
TEX = os.path.join(ROOT, "assets", "textures", "quaternius")
HIP = {"pistol": Vector((0.16, -0.15, -0.4)), "rifle": Vector((0.18, -0.2, -0.44))}  # Godot, WeaponHolder
COLORS = {"ArmGlove": (0.05, 0.05, 0.055), "ArmSuit": (0.08, 0.085, 0.1), "ArmAccent": (0.62, 0.27, 0.05)}


def g2b(v):
    return Vector((v.x, -v.z, v.y))


def import_into(path, coll_name, offset=Vector()):
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=path)
    coll = bpy.data.collections.new(coll_name)
    bpy.context.scene.collection.children.link(coll)
    for o in set(bpy.data.objects) - before:
        for c in list(o.users_collection):
            c.objects.unlink(o)
        coll.objects.link(o)
        if o.parent is None:
            o.location += offset
    return coll


def setup_materials():
    for m in bpy.data.materials:
        name = m.name.split(".")[0]
        m.use_nodes = True
        bsdf = m.node_tree.nodes.get("Principled BSDF")
        if not bsdf:
            continue
        if name in COLORS:
            bsdf.inputs["Base Color"].default_value = (*COLORS[name], 1)
            bsdf.inputs["Roughness"].default_value = 0.8
            m.diffuse_color = (*COLORS[name], 1)
        elif name == "MI_Guns_Batch1":
            for f in ("T_Guns_Batch1_BaseColor.jpg", "T_Guns_Batch1_BaseColor.png"):
                p = os.path.join(TEX, f)
                if os.path.exists(p):
                    img = bpy.data.images.load(p)
                    tn = m.node_tree.nodes.new("ShaderNodeTexImage")
                    tn.image = img
                    m.node_tree.links.new(tn.outputs["Color"], bsdf.inputs["Base Color"])
                    break


def build(gun):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    import_into(os.path.join(MODELS, gun + ".glb"), "Gun")
    import_into(os.path.join(MODELS, f"rigid_{gun}.glb"), "HandModel")
    import_into(os.path.join(MODELS, f"hands_{gun}.glb"), "Hands")
    bpy.context.view_layer.layer_collection.children["Hands"].hide_viewport = True
    arms = import_into(os.path.join(MODELS, f"arms_{gun}.glb"), "ArmsFull", g2b(-HIP[gun]))
    arms.hide_viewport = False
    bpy.context.view_layer.layer_collection.children["ArmsFull"].hide_viewport = True  # off by default
    setup_materials()
    # Game viewmodel camera: at the eye, i.e. -hip from the gun origin, looking down the barrel (+Y).
    cam_data = bpy.data.cameras.new("GameCamera")
    cam_data.sensor_fit = "VERTICAL"
    cam_data.angle_y = math.radians(54)
    cam_data.clip_start = 0.01
    cam = bpy.data.objects.new("GameCamera", cam_data)
    cam.location = g2b(-HIP[gun])
    cam.rotation_euler = (math.radians(90), 0, 0)
    cc = bpy.data.collections.new("GameCamera")
    bpy.context.scene.collection.children.link(cc)
    cc.objects.link(cam)
    sc = bpy.context.scene
    sc.camera = cam
    sc.render.resolution_x, sc.render.resolution_y = 1920, 1080
    sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", "SUN"))
    sun.rotation_euler = (math.radians(50), math.radians(10), math.radians(30))
    sun.data.energy = 4.0
    cc.objects.link(sun)
    world = bpy.data.worlds.new("World")
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.35, 0.37, 0.42, 1)
    sc.world = world
    sc.unit_settings.system = "METRIC"
    out = os.path.join(ROOT, "blender", f"hands_{gun}.blend")
    bpy.ops.file.make_paths_relative()
    bpy.ops.wm.save_as_mainfile(filepath=out, relative_remap=True)
    print("saved", out)


for g in HIP:
    build(g)
